create or replace function public._close_stale_shifts_for_org(p_org_id bigint)
returns integer language plpgsql security definer set search_path = public as $function$
declare
    v_tz text; v_trigger_hour integer; v_shift_hours numeric; v_notify boolean;
    v_local_now timestamp; v_count integer := 0; v_rec record;
begin
    select s.timezone, s.auto_close_trigger_hour, s.auto_close_shift_hours, s.notify_on_auto_close
      into v_tz, v_trigger_hour, v_shift_hours, v_notify
      from public.app_settings s where s.organisation_id = p_org_id;
    v_tz := coalesce(v_tz, 'UTC');
    v_trigger_hour := coalesce(v_trigger_hour, 23);
    v_shift_hours := coalesce(v_shift_hours, 8.5);
    v_local_now := (now() at time zone v_tz);
    for v_rec in
        with last_events as (
            select distinct on (ce.user_id) ce.id, ce.user_id, ce.event_type, ce.occurred_at
              from public.clock_events ce
             where ce.organisation_id = p_org_id and ce.occurred_at > now() - interval '48 hours'
             order by ce.user_id, ce.occurred_at desc
        )
        select le.user_id, le.occurred_at
          from last_events le
          join public.users u on u.id = le.user_id
         where le.event_type = 'in' and u.active
           and ((le.occurred_at at time zone v_tz)::date < v_local_now::date
               or extract(hour from v_local_now) >= v_trigger_hour)
    loop
        insert into public.clock_events (user_id, event_type, occurred_at, source, auto_closed, organisation_id)
        values (v_rec.user_id, 'out',
            v_rec.occurred_at + make_interval(mins => (v_shift_hours * 60)::int),
            'auto-close', true, p_org_id);
        v_count := v_count + 1;
        if v_notify then
            insert into public.pending_notifications (user_id, kind, payload, organisation_id)
            select v_rec.user_id, 'auto_close',
                   jsonb_build_object('in_at', v_rec.occurred_at,
                       'out_at', v_rec.occurred_at + make_interval(mins => (v_shift_hours * 60)::int)),
                   p_org_id
             where exists (select 1 from public.users u where u.id = v_rec.user_id and u.email is not null);
        end if;
    end loop;
    return v_count;
end$function$;

