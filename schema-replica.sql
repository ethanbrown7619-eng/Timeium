create or replace function public.create_first_organisation(p_org_name text, p_slug text default null)
returns bigint language plpgsql security definer set search_path = public as $function$
declare
    v_user_id uuid := auth.uid();
    v_slug text; v_slug_try text; v_org_id bigint; v_try integer := 0;
begin
    if v_user_id is null then raise exception 'must be signed in'; end if;
    if exists (select 1 from public.admins where user_id = v_user_id) then
        raise exception 'already an admin of an organisation';
    end if;
    if p_org_name is null or length(trim(p_org_name)) = 0 then
        raise exception 'organisation name is required';
    end if;
    v_slug := coalesce(
        nullif(lower(regexp_replace(trim(coalesce(p_slug, '')), '[^a-zA-Z0-9]+', '-', 'g')), ''),
        lower(regexp_replace(trim(p_org_name), '[^a-zA-Z0-9]+', '-', 'g'))
    );
    v_slug := regexp_replace(v_slug, '^-+|-+$', '', 'g');
    if length(v_slug) = 0 then v_slug := 'org'; end if;
    v_slug_try := v_slug;
    loop
        begin
            insert into public.organisations (slug, name) values (v_slug_try, trim(p_org_name)) returning id into v_org_id;
            exit;
        exception when unique_violation then
            v_try := v_try + 1;
            if v_try > 20 then raise exception 'could not allocate unique slug from %', p_org_name; end if;
            v_slug_try := v_slug || '-' || (v_try + 1)::text;
        end;
    end loop;
    insert into public.admins (user_id, organisation_id, role) values (v_user_id, v_org_id, 'admin');
    insert into public.app_settings (organisation_id) values (v_org_id) on conflict do nothing;
    return v_org_id;
end$function$;

create or replace function public.claim_employee_by_email()
returns jsonb language plpgsql security definer set search_path = public as $function$
declare v_auth_email text; v_existing public.users; v_candidate public.users;
begin
    select * into v_existing from public.users where auth_user_id = auth.uid() limit 1;
    if v_existing.id is not null then
        return jsonb_build_object('claimed', true, 'already_linked', true,
            'user_id', v_existing.id, 'organisation_id', v_existing.organisation_id, 'name', v_existing.name);
    end if;
    select email into v_auth_email from auth.users where id = auth.uid();
    if v_auth_email is null then raise exception 'Not signed in'; end if;
    select * into v_candidate from public.users
        where auth_user_id is null and email is not null and lower(email) = lower(v_auth_email) limit 1;
    if v_candidate.id is null then
        return jsonb_build_object('claimed', false, 'reason', 'no_match', 'email', v_auth_email);
    end if;
    update public.users set auth_user_id = auth.uid() where id = v_candidate.id;
    return jsonb_build_object('claimed', true, 'already_linked', false,
        'user_id', v_candidate.id, 'organisation_id', v_candidate.organisation_id, 'name', v_candidate.name);
end$function$;

