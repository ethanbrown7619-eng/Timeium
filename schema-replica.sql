create or replace function public.generate_nz_public_holidays(p_year integer)
returns table(holiday_date date, name text) language plpgsql stable set search_path = public as $function$
declare
    v_a int; v_b int; v_c int; v_d int; v_e int; v_f int;
    v_g int; v_h int; v_i int; v_k int; v_l int; v_m int;
    v_month int; v_day int; v_easter date;
    v_d1 date; v_d2 date; v_dow1 int; v_obs1 date; v_obs2 date; v_matariki date;
begin
    v_a := p_year % 19; v_b := p_year / 100; v_c := p_year % 100;
    v_d := v_b / 4; v_e := v_b % 4; v_f := (v_b + 8) / 25;
    v_g := (v_b - v_f + 1) / 3;
    v_h := (19 * v_a + v_b - v_d - v_g + 15) % 30;
    v_i := v_c / 4; v_k := v_c % 4;
    v_l := (32 + 2 * v_e + 2 * v_i - v_h - v_k) % 7;
    v_m := (v_a + 11 * v_h + 22 * v_l) / 451;
    v_month := (v_h + v_l - 7 * v_m + 114) / 31;
    v_day := ((v_h + v_l - 7 * v_m + 114) % 31) + 1;
    v_easter := make_date(p_year, v_month, v_day);
    holiday_date := v_easter - 2; name := 'Good Friday'; return next;
    holiday_date := v_easter + 1; name := 'Easter Monday'; return next;
