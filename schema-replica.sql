create or replace function public.apply_leave_to_timesheet(p_request_id bigint)
returns void language plpgsql security definer set search_path = public, extensions as $function$
declare
    v_req public.leave_requests; v_job_id bigint; v_day date; v_week_start date;
    v_ts_id bigint; v_entry_id bigint; v_dow int; v_col text;
    v_locked_weeks date[]; v_applied_any boolean := false;
begin
    select * into v_req from public.leave_requests where id = p_request_id;
    if v_req.id is null then raise exception 'Leave request not found'; end if;
    if not public.is_manager_of(v_req.organisation_id) then raise exception 'Not authorised'; end if;
    select array_agg(t.week_start order by t.week_start) into v_locked_weeks
      from public.timesheets t
      join (
          select distinct (gs::date - (extract(isodow from gs)::int - 1))::date as wk
            from generate_series(v_req.start_date, v_req.end_date, '1 day'::interval) gs
           where not (v_req.skip_weekends and extract(isodow from gs) >= 6)
      ) weeks on weeks.wk = t.week_start
     where t.user_id = v_req.user_id and t.status in ('submitted','approved');
    if v_locked_weeks is not null and array_length(v_locked_weeks, 1) > 0 then
        raise exception 'Cannot apply leave: timesheets already submitted/approved for week(s) %. Un-submit them first, then retry.',
            array_to_string(v_locked_weeks, ', ');
    end if;
    select j.id into v_job_id from public.jobs j
      where j.organisation_id = v_req.organisation_id and j.is_leave = true and j.leave_type_id = v_req.leave_type_id limit 1;
    if v_job_id is null then
        raise exception 'No leave job configured for this leave type. Ask an admin to create one in Configure > Jobs.';
    end if;
    v_day := v_req.start_date;
    while v_day <= v_req.end_date loop
        v_dow := extract(isodow from v_day)::int;
        if v_req.skip_weekends and v_dow >= 6 then v_day := v_day + 1; continue; end if;
        v_week_start := v_day - (v_dow - 1);
        select id into v_ts_id from public.timesheets where user_id = v_req.user_id and week_start = v_week_start limit 1;
        if v_ts_id is null then
            insert into public.timesheets (organisation_id, user_id, week_start, status)
              values (v_req.organisation_id, v_req.user_id, v_week_start, 'draft') returning id into v_ts_id;
        end if;
        select id into v_entry_id from public.timesheet_entries where timesheet_id = v_ts_id and job_id = v_job_id limit 1;
        if v_entry_id is null then
            insert into public.timesheet_entries (timesheet_id, job_id, description)
              values (v_ts_id, v_job_id,
                case when v_req.reason is not null and trim(v_req.reason) <> '' then v_req.reason else null end)
              returning id into v_entry_id;
        end if;
        v_col := case v_dow when 1 then 'mon_hours' when 2 then 'tue_hours' when 3 then 'wed_hours'
            when 4 then 'thu_hours' when 5 then 'fri_hours' when 6 then 'sat_hours' when 7 then 'sun_hours' end;
        execute format('update public.timesheet_entries set %I = $1 where id = $2', v_col)
          using v_req.hours_per_day, v_entry_id;
        v_applied_any := true;
        v_day := v_day + 1;
    end loop;
    if not v_applied_any then
        raise exception 'Leave request would write zero entries (every day in the range is a skipped weekend).';
    end if;
    update public.leave_requests set applied_to_timesheet = true, applied_at = now() where id = p_request_id;
end$function$;

create or replace function public.clear_leave_from_timesheet(p_request_id bigint)
returns void language plpgsql security definer set search_path = public, extensions as $function$
declare
    v_req public.leave_requests; v_job_id bigint; v_day date; v_week_start date;
    v_ts_id bigint; v_entry_id bigint; v_dow int; v_col text; v_locked_weeks date[];
begin
    select * into v_req from public.leave_requests where id = p_request_id;
    if v_req.id is null then raise exception 'Leave request not found'; end if;
    if not public.is_manager_of(v_req.organisation_id) then raise exception 'Not authorised'; end if;
    select array_agg(t.week_start order by t.week_start) into v_locked_weeks
      from public.timesheets t
      join (
          select distinct (gs::date - (extract(isodow from gs)::int - 1))::date as wk
            from generate_series(v_req.start_date, v_req.end_date, '1 day'::interval) gs
           where not (v_req.skip_weekends and extract(isodow from gs) >= 6)
      ) weeks on weeks.wk = t.week_start
     where t.user_id = v_req.user_id and t.status in ('submitted','approved');
    if v_locked_weeks is not null and array_length(v_locked_weeks, 1) > 0 then
        raise exception 'Cannot modify or revoke this leave: it has hours on submitted/approved timesheet(s) for week(s) %. Un-submit those weeks first, then retry.',
            array_to_string(v_locked_weeks, ', ');
    end if;
    select j.id into v_job_id from public.jobs j
      where j.organisation_id = v_req.organisation_id and j.is_leave = true and j.leave_type_id = v_req.leave_type_id limit 1;
    if v_job_id is null then return; end if;
    v_day := v_req.start_date;
    while v_day <= v_req.end_date loop
        v_dow := extract(isodow from v_day)::int;
        if v_req.skip_weekends and v_dow >= 6 then v_day := v_day + 1; continue; end if;
        v_week_start := v_day - (v_dow - 1);
        select id into v_ts_id from public.timesheets where user_id = v_req.user_id and week_start = v_week_start limit 1;
        if v_ts_id is not null then
            select id into v_entry_id from public.timesheet_entries where timesheet_id = v_ts_id and job_id = v_job_id limit 1;
            if v_entry_id is not null then
                v_col := case v_dow when 1 then 'mon_hours' when 2 then 'tue_hours' when 3 then 'wed_hours'
                    when 4 then 'thu_hours' when 5 then 'fri_hours' when 6 then 'sat_hours' when 7 then 'sun_hours' end;
                execute format('update public.timesheet_entries set %I = 0 where id = $1', v_col) using v_entry_id;
                delete from public.timesheet_entries where id = v_entry_id
                  and mon_hours = 0 and tue_hours = 0 and wed_hours = 0
                  and thu_hours = 0 and fri_hours = 0 and sat_hours = 0 and sun_hours = 0;
            end if;
        end if;
        v_day := v_day + 1;
    end loop;
end$function$;

create or replace function public.approve_leave_request(p_request_id bigint, p_note text default null)
